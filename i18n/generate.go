// Standalone generator: go run i18n/generate.go [-check] (from repository root).
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

func main() {
	check := flag.Bool("check", false, "verify that committed adapters match the catalog")
	flag.Parse()
	raw, err := os.ReadFile("i18n/catalog.json")
	if err != nil { fail(err) }
	var catalog map[string]map[string]string
	if err = json.Unmarshal(raw, &catalog); err != nil { fail(err) }
	en, ok := catalog["en-US"]
	if !ok || len(catalog) != 2 { fail(fmt.Errorf("expected exactly en-US and zh-CN catalogs")) }
	zh, ok := catalog["zh-CN"]
	if !ok || len(zh) != len(en) { fail(fmt.Errorf("language catalogs differ in size")) }
	keys := make([]string, 0, len(en))
	for key, english := range en {
		if english == "" || zh[key] == "" { fail(fmt.Errorf("missing translation for %q", key)) }
		if placeholders(english) != placeholders(zh[key]) { fail(fmt.Errorf("placeholder mismatch: %s", key)) }
		keys = append(keys, key)
	}
	sort.Strings(keys)
	goOut := &bytes.Buffer{}
	fmt.Fprintln(goOut, "// Code generated by i18n/generate.go; DO NOT EDIT.\npackage i18n\n")
	fmt.Fprintln(goOut, "var catalog = map[string]map[string]string{")
	tsOut := &bytes.Buffer{}
	fmt.Fprintln(tsOut, "// Code generated by i18n/generate.go; DO NOT EDIT.")
	fmt.Fprintln(tsOut, "export const catalog = {")
	for _, locale := range []string{"en-US", "zh-CN"} {
		fmt.Fprintf(goOut, "\t%q: {\n", locale)
		fmt.Fprintf(tsOut, "  %q: {\n", locale)
		for _, key := range keys {
			value := catalog[locale][key]
			quotedKey := quote(key)
			quotedValue := quote(value)
			fmt.Fprintf(goOut, "\t\t%s: %s,\n", quotedKey, quotedValue)
			fmt.Fprintf(tsOut, "    %s: %s,\n", quotedKey, quotedValue)
		}
		fmt.Fprintln(goOut, "\t},")
		fmt.Fprintln(tsOut, "  },")
	}
	fmt.Fprintln(goOut, "}")
	fmt.Fprintln(tsOut, "} as const;\nexport type MessageKey = keyof typeof catalog[\"en-US\"];")
	
	goBytes, err := format.Source(goOut.Bytes())
	if err != nil { fail(fmt.Errorf("format generated Go catalog: %w", err)) }
	outputs := map[string][]byte{
		"cetas-go/internal/i18n/generated.go": goBytes,
		"cetas-js/src/i18n/generated.ts": tsOut.Bytes(),
	}
	for path, content := range outputs {
		if *check {
			previous, err := os.ReadFile(path)
			if err != nil {
				fail(fmt.Errorf("%s is stale; run go run i18n/generate.go", path))
			}
			// Both adapters are compared as generated bytes: the TypeScript
			// adapter is not Go source and must never be parsed by go/format.
			if !bytes.Equal(previous, content) {
				fail(fmt.Errorf("%s is stale; run go run i18n/generate.go", path))
			}
		} else if err := os.WriteFile(path, content, 0644); err != nil {
			fail(err)
		}
	}
}
func placeholders(s string) string {
	var parts []string
	for {
		begin := strings.IndexByte(s, '{')
		if begin < 0 { break }
		end := strings.IndexByte(s[begin+1:], '}')
		if end < 0 { break }
		name := s[begin+1 : begin+end+1]
		if name != "" && !strings.ContainsAny(name, "{} \t\n") { parts = append(parts, name) }
		s = s[begin+end+2:]
	}
	sort.Strings(parts)
	return strings.Join(parts, ",")
}
func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }

func quote(input string) string {
 var output bytes.Buffer
 encoder := json.NewEncoder(&output)
 encoder.SetEscapeHTML(false)
 if err := encoder.Encode(input); err != nil { fail(err) }
 return strings.TrimSuffix(output.String(), "\n")
}
