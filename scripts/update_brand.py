#!/usr/bin/env python3
"""Regenerate Cetas SVG assets and its terminal cut; --check detects drift."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
# Integer lattice; all edges are horizontal, vertical or +/-45 degrees.
# The two cuts have normal width 1/sqrt(2): x+y=10/11 and y-x=5/6.
MASTER = [
    [(6, 0), (10, 0), (0, 10), (0, 6)],
    [(11, 0), (22, 0), (18, 4), (7, 4)],
    [(0, 11), (4, 7), (4, 16), (6, 18), (12, 18), (16, 22), (6, 22), (0, 16)],
    [(12, 17), (17, 17), (22, 22), (17, 22)],
]
# Optical cut for favicons/terminal cells: double BOTH gaps, keep the silhouette.
SMALL = [
    MASTER[0],
    [(12, 0), (22, 0), (18, 4), (8, 4)],
    [(0, 12), (4, 8), (4, 16), (6, 18), (12, 18), (16, 22), (6, 22), (0, 16)],
    [(13, 17), (17, 17), (22, 22), (18, 22)],
]


def svg(polygons, color: str, adaptive: bool = False) -> str:
    style = '<style>polygon{fill:#256C63}@media(prefers-color-scheme:dark){polygon{fill:#DDF2E6}}</style>' if adaptive else ''
    paths = ''.join('<polygon points="' + ' '.join(f'{x},{y}' for x, y in p) + '"/>' for p in polygons)
    return ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="-3 -3 28 28" '
            'width="256" height="256" role="img"><title>Cetas - Modular Cut symbol</title>'
            + style + f'<g fill="{color}">' + paths + '</g></svg>\n')


def contains(p, x: float, y: float) -> bool:
    odd = False
    for (ax, ay), (bx, by) in zip(p, p[1:] + p[:1]):
        if (ay > y) != (by > y) and x < (bx-ax)*(y-ay)/(by-ay)+ax:
            odd = not odd
    return odd


def terminal_rows() -> list[str]:
    # A cell is roughly twice as tall as wide: 12 columns x 6 half-block rows.
    pixels = [[any(contains(p, (x+.5)*22/12, (y+.5)*22/12) for p in SMALL)
               for x in range(12)] for y in range(12)]
    return [''.join(' ▀▄█'[int(a) + 2*int(b)] for a, b in zip(pixels[y], pixels[y+1]))
            for y in range(0, 12, 2)]


def outputs() -> dict[Path, str]:
    rows = '\n'.join('  ' + json.dumps(row, ensure_ascii=False) + ',' for row in terminal_rows())
    return {
        ROOT/'docs/assets/cetas-symbol.svg': svg(MASTER, '#256C63'),
        ROOT/'docs/assets/cetas-symbol-dark.svg': svg(MASTER, '#DDF2E6'),
        ROOT/'cetas-website/public/cetas-logo.svg': svg(MASTER, '#256C63', adaptive=True),
        ROOT/'cetas-website/public/favicon.svg': svg(SMALL, '#256C63', adaptive=True),
        ROOT/'cetas-js/ui/brand-mark.ts': '// Generated by scripts/update_brand.py; do not edit by hand.\n'
            '// Optical six-row cut of the Modular Cut mark, using half-block cells.\n'
            'export const MODULAR_CUT = [\n' + rows + '\n] as const;\n',
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for path, content in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        print('Brand assets need regeneration: ' + ', '.join(stale))
        return 1
    print('Brand assets are up to date.' if args.check else 'Regenerated brand assets.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
